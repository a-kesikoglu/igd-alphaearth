"""Build the compact repository archive (fewer than 100 files) for upload to GitHub.

- figures: vector PDF only (PNG versions are regenerated by the figure scripts);
- tables: all CSV tables combined in outputs/tables/tables.xlsx (one sheet per table);
- run logs: merged into reports/run_logs.txt;
- data/processed/samples.parquet is omitted (regenerated by 02_prepare.py, the first step of reproduce_all.py);
- outputs/metrics/e1_predictions.npz is omitted (same content as predictions_long.parquet; regenerated by 03_experiments.py).
Writes ../igd-alphaearth.zip next to the project folder."""
import zipfile
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
T = ROOT / "outputs/tables"; R = ROOT / "reports"

with pd.ExcelWriter(T / "tables.xlsx") as xw:
    for f in sorted(T.glob("*.csv")):
        pd.read_csv(f, dtype=str, keep_default_na=False).to_excel(xw, sheet_name=f.stem[:31], index=False)

logs = ["export_log.txt", "qc_s1_log.txt", "experiment_log.txt", "stats_log.txt"]
with open(R / "run_logs.txt", "w", encoding="utf-8") as out:
    for f in logs:
        if (R / f).exists():
            out.write(f"===== {f} =====\n" + (R / f).read_text(encoding="utf-8", errors="replace") + "\n")

SKIP_DIRS = {"__pycache__", "literature"}
SKIP_FILES = {"reports/gates.json", "outputs/old_05_figures_results.py.bak", "outputs/metrics/e1_summary_prev.csv",
              "outputs/metrics/e1_summary_v1.csv", "outputs/metrics/e1_predictions.npz", "docs/Extended_Results.docx", "data/processed/samples.parquet",
              "Makefile"} | {f"reports/{f}" for f in logs}


def keep(p: Path) -> bool:
    rel = p.relative_to(ROOT).as_posix()
    if p.is_dir() or SKIP_DIRS & set(p.relative_to(ROOT).parts) or rel in SKIP_FILES:
        return False
    if rel.startswith("manuscript/") and p.suffix in (".docx", ".pdf"):
        return False
    if rel.startswith("outputs/figures/") and p.suffix == ".png":
        return False
    if rel.startswith("outputs/tables/") and p.suffix == ".csv":
        return False
    return True


files = [p for p in sorted(ROOT.rglob("*")) if keep(p)]
out = ROOT.parent / "igd-alphaearth.zip"
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    for p in files:
        z.write(p, "igd-alphaearth/" + p.relative_to(ROOT).as_posix())
print(len(files), "files,", round(out.stat().st_size / 1e6, 1), "MB")
for p in files:
    print(" ", p.relative_to(ROOT).as_posix())
